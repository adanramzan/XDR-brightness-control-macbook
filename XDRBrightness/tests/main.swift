import Foundation
func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    guard condition() else { fatalError(message) }
}
check(BoostPolicy.supported(builtIn: true, headroom: 3.2), "Built-in XDR must be supported")
check(!BoostPolicy.supported(builtIn: false, headroom: 3.2), "Do not overlay external screens")
check(!BoostPolicy.supported(builtIn: true, headroom: 1), "SDR cannot boost")
check(!BoostPolicy.supported(builtIn: true, headroom: .nan), "Invalid headroom cannot boost")
check(!BoostPolicy.supported(builtIn: true, headroom: .infinity), "Invalid headroom cannot boost")
check(BoostPolicy.gain(level: 0) == 1, "Lowest slider position is neutral")
check(abs(BoostPolicy.gain(level: 1) - 3.2) < 0.001, "Peak target is 3.2x SDR")
check(BoostPolicy.gain(level: -1) == 1, "Scrolling below neutral must clamp")
check(BoostPolicy.gain(level: 2) == 3.2, "Scrolling above peak must clamp")
check(BoostPolicy.gain(level: .nan) == 1, "Invalid gain must be neutral")
check(BoostPolicy.estimatedNits(brightness: 0, level: 1) == 0, "Zero hardware output stays zero")
check(abs(BoostPolicy.estimatedNits(brightness: 0.5, level: 0) - 140) < 0.01, "Use calibrated SDR midpoint, not linear percentage")
check(abs(BoostPolicy.estimatedNits(brightness: 1, level: 0) - 500) < 0.01, "Native M1 XDR SDR maximum estimate")
check(abs(BoostPolicy.estimatedNits(brightness: 1, level: 1) - 1600) < 0.01, "Peak estimate")
check(BoostPolicy.scrolledLevel(0.99, delta: 20) == 1, "Scroll clamps at peak")
check(BoostPolicy.scrolledLevel(0.01, delta: -20) == 0, "Scroll clamps at neutral")
print("16 boost, scroll and nits checks passed")
check(BoostPolicy.keyStep(brightness: 0.9, level: 0, increase: true, fine: false) == nil, "Leave native F2 alone below SDR peak")
check(BoostPolicy.keyStep(brightness: 1, level: 0, increase: true, fine: false) == 0.0625, "F2 enters XDR at SDR maximum")
check(BoostPolicy.keyStep(brightness: 1, level: 0.5, increase: true, fine: false) == 0.5625, "F2 continues through XDR")
check(BoostPolicy.keyStep(brightness: 1, level: 1, increase: true, fine: false) == 1, "F2 clamps at XDR maximum")
check(BoostPolicy.keyStep(brightness: 1, level: 0.5, increase: false, fine: false) == 0.4375, "F1 reduces boost before hardware")
check(BoostPolicy.keyStep(brightness: 1, level: 0.02, increase: false, fine: false) == 0, "F1 lands on SDR boundary")
check(BoostPolicy.keyStep(brightness: 1, level: 0, increase: false, fine: false) == nil, "F1 returns to native below XDR")
check(BoostPolicy.keyStep(brightness: 1, level: 0, increase: true, fine: true) == 0.015625, "Option Shift fine increments")
check(BoostPolicy.keyStep(brightness: .nan, level: 0, increase: true, fine: false) == nil, "Unreadable brightness cannot intercept keys")
print("9 SDR-to-XDR key transition checks passed")
check(BoostPolicy.gammaFactor(gain: 1, headroom: 3.2) == 1, "Neutral gain leaves gamma untouched")
check(abs(BoostPolicy.gammaFactor(gain: 3.2, headroom: 3.2) - pow(3.2, 1 / 2.2)) < 0.0001, "Peak gain maps to encoded gamma factor")
check(BoostPolicy.gammaFactor(gain: 3.2, headroom: 1) == 1, "No EDR headroom means no gamma boost")
check(abs(BoostPolicy.gammaFactor(gain: 3.2, headroom: 2) - pow(2, 1 / 2.2)) < 0.0001, "Gamma boost is capped at current headroom")
check(BoostPolicy.gammaFactor(gain: .nan, headroom: 3.2) == 1, "Invalid gain cannot boost gamma")
print("5 gamma factor checks passed")
var gate = KeyGate()
gate.press(2, handled: true); gate.press(2, handled: true)
check(gate.release(2), "Fully consumed XDR press swallows its release")
gate.press(2, handled: false); gate.press(2, handled: true)
check(!gate.release(2), "SDR press crossing into XDR must give macOS its release")
gate.press(3, handled: true); gate.press(3, handled: false)
check(!gate.release(3), "XDR press falling back to native dimming must give macOS its release")
check(!gate.release(3), "Unseen release passes through")
print("4 key release checks passed")
